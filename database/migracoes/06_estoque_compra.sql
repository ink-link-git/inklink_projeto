-- Módulo estoque_tatuador (rode depois do 05_estoque.sql).
-- Rode no SQL Editor do Supabase. Pode rodar mais de uma vez (usa IF NOT EXISTS).

CREATE TABLE IF NOT EXISTS estoque_compra (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tatuador      UUID NOT NULL,              -- tatuador.id_tatuador
    item_id          BIGINT REFERENCES estoque_item(id) ON DELETE SET NULL,
    nome_item        TEXT NOT NULL,              -- copiado, para o histórico não mudar se o item for editado
    quantidade       INT NOT NULL CHECK (quantidade > 0),
    unidade          TEXT NOT NULL,
    unidade_singular TEXT NOT NULL,
    data_compra      DATE NOT NULL,
    criado_em        TIMESTAMP DEFAULT NOW()
);

-- Se você já rodou uma versão anterior deste arquivo, remove a coluna de valor (fora do escopo do projeto).
ALTER TABLE estoque_compra DROP COLUMN IF EXISTS valor;

CREATE INDEX IF NOT EXISTS idx_estoque_compra_tatuador ON estoque_compra (id_tatuador, data_compra DESC);

