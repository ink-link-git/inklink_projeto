-- Se 'anamnese' já existia com outro formato, ela só é renomeada (nada é apagado).
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = 'anamnese')
       AND NOT EXISTS (SELECT 1 FROM information_schema.columns
                       WHERE table_schema = 'public' AND table_name = 'anamnese' AND column_name = 'agendamento_id') THEN
        ALTER TABLE anamnese RENAME TO anamnese_antiga;
    END IF;
END $$;


-- 3. FICHA DE ANAMNESE ------------------------------------------------------
CREATE TABLE IF NOT EXISTS anamnese (
    id                            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agendamento_id                BIGINT NOT NULL UNIQUE REFERENCES agendamento(id) ON DELETE CASCADE,
    cliente_id                    UUID NOT NULL,
    data_preenchimento            TIMESTAMP DEFAULT NOW(),

    possui_alergia                BOOLEAN NOT NULL DEFAULT FALSE,
    descricao_alergia             TEXT,
    possui_doenca_pele            BOOLEAN NOT NULL DEFAULT FALSE,
    descricao_doenca_pele         TEXT,
    diabetico                     BOOLEAN NOT NULL DEFAULT FALSE,
    hemofilico                    BOOLEAN NOT NULL DEFAULT FALSE,
    cardiopata                    BOOLEAN NOT NULL DEFAULT FALSE,
    epileptico                    BOOLEAN NOT NULL DEFAULT FALSE,
    hipertenso                    BOOLEAN NOT NULL DEFAULT FALSE,
    faz_uso_medicamento           BOOLEAN NOT NULL DEFAULT FALSE,
    descricao_medicamento         TEXT,
    usa_anticoagulante            BOOLEAN NOT NULL DEFAULT FALSE,
    gestante                      BOOLEAN NOT NULL DEFAULT FALSE,
    ja_fez_tatuagem               BOOLEAN NOT NULL DEFAULT FALSE,
    teve_reacao_tatuagem_anterior BOOLEAN NOT NULL DEFAULT FALSE,
    descricao_reacao              TEXT,
    consome_alcool_drogas         BOOLEAN NOT NULL DEFAULT FALSE,

    ciente_riscos                 BOOLEAN NOT NULL DEFAULT TRUE,
    termo_aceito                  BOOLEAN NOT NULL DEFAULT TRUE,
    observacoes                   TEXT
);
