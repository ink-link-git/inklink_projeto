-- InkLink — estoque do tatuador
-- Módulo estoque_tatuador.
-- Rode no SQL Editor do Supabase. Pode rodar mais de uma vez (usa IF NOT EXISTS).

CREATE TABLE IF NOT EXISTS estoque_item (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tatuador      UUID NOT NULL,              -- tatuador.id_tatuador
    categoria        TEXT NOT NULL,              -- TINTA | AGULHA | CURATIVO | MATERIAL
    nome             TEXT NOT NULL,
    quantidade       INT  NOT NULL DEFAULT 0 CHECK (quantidade >= 0),
    unidade          TEXT NOT NULL,              -- plural (frascos, unid., potes...)
    unidade_singular TEXT NOT NULL               -- singular (frasco, unid., pote...)
);

CREATE TABLE IF NOT EXISTS estoque_uso (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tatuador  UUID NOT NULL,
    cliente      TEXT NOT NULL,
    data_sessao  DATE NOT NULL,
    criado_em    TIMESTAMP DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS estoque_uso_item (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uso_id           BIGINT NOT NULL REFERENCES estoque_uso(id) ON DELETE CASCADE,
    item_id          BIGINT REFERENCES estoque_item(id) ON DELETE SET NULL,
    nome_item        TEXT NOT NULL,              -- copiado, para o histórico não mudar se o item for editado
    quantidade       INT NOT NULL CHECK (quantidade > 0),
    unidade          TEXT NOT NULL,
    unidade_singular TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_estoque_item_tatuador ON estoque_item (id_tatuador);
CREATE INDEX IF NOT EXISTS idx_estoque_uso_tatuador  ON estoque_uso (id_tatuador, data_sessao DESC);

