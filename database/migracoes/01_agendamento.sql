-- InkLink — agendamento
-- Tabelas: agendamento e referencia_visual (módulos agendamento_cliente e agendamento_tatuador).
-- Rode no SQL Editor do Supabase. Pode rodar mais de uma vez (usa IF NOT EXISTS).
-- As tabelas 'cliente', 'tatuador' e 'portfolio' já existem e não são alteradas aqui.

-- Se 'referencia_visual' já existia com outro formato, ela só é renomeada (nada é apagado).
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = 'referencia_visual')
       AND NOT EXISTS (SELECT 1 FROM information_schema.columns
                       WHERE table_schema = 'public' AND table_name = 'referencia_visual' AND column_name = 'agendamento_id') THEN
        ALTER TABLE referencia_visual RENAME TO referencia_visual_antiga;
    END IF;
END $$;


-- 1. AGENDAMENTO ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS agendamento (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_auth_id UUID NOT NULL,             -- cliente.auth_id (id do usuário no Supabase Auth)
    id_tatuador UUID NOT NULL,                 -- tatuador.id_tatuador
    data_desejada DATE NOT NULL,               -- dia que o cliente pediu
    periodo     TEXT DEFAULT 'qualquer',       -- manha | tarde | noite | qualquer (preferência do cliente)
    data_hora   TIMESTAMP,                     -- horário exato, definido pelo tatuador ao aceitar
    duracao_min INT,                           -- duração prevista, definida pelo tatuador ao aceitar
    status      TEXT NOT NULL DEFAULT 'PENDENTE'  -- PENDENTE | CONFIRMADO | CANCELADO | REALIZADO
);

-- Se a tabela antiga tinha 'id_tatuador' ou 'cliente_auth_id' como número (bigint/int), o
-- Supabase recusa o UUID. Nesse caso a coluna é recriada como UUID (só essa coluna perde
-- o valor antigo; os ids numéricos da agenda antiga não servem para o sistema novo).
DO $$
DECLARE col TEXT;
BEGIN
    FOREACH col IN ARRAY ARRAY['id_tatuador', 'cliente_auth_id']
    LOOP
        IF EXISTS (SELECT 1 FROM information_schema.columns
                   WHERE table_schema = 'public' AND table_name = 'agendamento'
                     AND column_name = col AND data_type <> 'uuid') THEN
            EXECUTE format('ALTER TABLE agendamento DROP COLUMN %I CASCADE', col);
            EXECUTE format('ALTER TABLE agendamento ADD COLUMN %I UUID', col);
            RAISE NOTICE 'Coluna agendamento.% recriada como UUID', col;
        END IF;
    END LOOP;
END $$;

-- Se a tabela já existia (da agenda antiga), só acrescenta o que falta.
-- A agenda antiga tinha 'cliente_id' como número (bigint). Ela não é mexida: o novo código usa
-- 'cliente_auth_id' (UUID do Supabase Auth) e a coluna antiga só deixa de ser obrigatória.
ALTER TABLE agendamento ADD COLUMN IF NOT EXISTS cliente_auth_id UUID;
DO $$
DECLARE col TEXT;
BEGIN
    FOREACH col IN ARRAY ARRAY['cliente_id', 'id_cliente', 'servico', 'especialidade', 'profissional', 'data_hora', 'data_hora_inicio', 'data_hora_fim', 'id_ideia']
    LOOP
        IF EXISTS (SELECT 1 FROM information_schema.columns
                   WHERE table_schema = 'public' AND table_name = 'agendamento' AND column_name = col) THEN
            EXECUTE format('ALTER TABLE agendamento ALTER COLUMN %I DROP NOT NULL', col);
        END IF;
    END LOOP;
END $$;
ALTER TABLE agendamento ADD COLUMN IF NOT EXISTS id_tatuador   UUID;
ALTER TABLE agendamento ADD COLUMN IF NOT EXISTS data_desejada DATE;
ALTER TABLE agendamento ADD COLUMN IF NOT EXISTS periodo       TEXT DEFAULT 'qualquer';
ALTER TABLE agendamento ADD COLUMN IF NOT EXISTS data_hora     TIMESTAMP;
ALTER TABLE agendamento ADD COLUMN IF NOT EXISTS duracao_min   INT;
ALTER TABLE agendamento ADD COLUMN IF NOT EXISTS status        TEXT DEFAULT 'PENDENTE';
ALTER TABLE agendamento ADD COLUMN IF NOT EXISTS cor_pele      TEXT;
ALTER TABLE agendamento ADD COLUMN IF NOT EXISTS descricao     TEXT;   -- ideia da tatuagem, escrita pelo cliente
ALTER TABLE agendamento ADD COLUMN IF NOT EXISTS observacoes   TEXT;
ALTER TABLE agendamento ADD COLUMN IF NOT EXISTS servico       TEXT;
ALTER TABLE agendamento ADD COLUMN IF NOT EXISTS especialidade TEXT;
ALTER TABLE agendamento ADD COLUMN IF NOT EXISTS profissional  TEXT;

-- Pedido novo ainda não tem horário: data_hora passa a ser opcional.
ALTER TABLE agendamento ALTER COLUMN data_hora DROP NOT NULL;

-- Linhas antigas (agenda antiga) ficam com o dia pedido = dia do horário que já tinham.
UPDATE agendamento SET data_desejada = data_hora::date WHERE data_desejada IS NULL AND data_hora IS NOT NULL;

-- (versão anterior desta migração criava um horário fixo único; não vale mais)
DROP INDEX IF EXISTS ux_agendamento_horario;

-- Duas sessões CONFIRMADAS do mesmo tatuador não podem começar no mesmo instante.
-- A checagem de sobreposição completa (considerando a duração) é feita pelo servidor.
CREATE UNIQUE INDEX IF NOT EXISTS ux_agendamento_inicio_confirmado
    ON agendamento (id_tatuador, data_hora)
    WHERE status = 'CONFIRMADO';

CREATE INDEX IF NOT EXISTS ix_agendamento_dia ON agendamento (id_tatuador, data_desejada);

CREATE INDEX IF NOT EXISTS ix_agendamento_cliente ON agendamento (cliente_auth_id);

-- 2. IMAGENS DE REFERÊNCIA DO CLIENTE --------------------------------------
CREATE TABLE IF NOT EXISTS referencia_visual (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agendamento_id BIGINT NOT NULL REFERENCES agendamento(id) ON DELETE CASCADE,
    caminho_imagem TEXT NOT NULL,
    data_upload    TIMESTAMP DEFAULT NOW()
);

